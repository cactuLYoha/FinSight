const assert = require('node:assert/strict');
const { randomUUID, createHash } = require('node:crypto');
const { lookup } = require('node:dns/promises');
const { readFile } = require('node:fs/promises');
const { chromium } = require('playwright');
if (!process.env.TEST_MAIL_DIR) throw new Error('Use isolated verification Compose with a test outbox.');
const base = process.env.BASE_URL || 'http://localhost:4201';
(async () => {
  const host = await lookup('host.docker.internal', { family: 4 });
  const browser = await chromium.launch({ args: ['--no-sandbox', '--host-resolver-rules=MAP localhost ' + host.address] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [], writes = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('response', response => { if (response.url().includes('/api/savings/') && response.request().method() !== 'GET') writes.push([response.request().method(), new URL(response.url()).pathname, response.status()]); });
  try {
    const email = 'savings-' + randomUUID() + '@example.com';
    await page.goto(base + '/register');
    const notice = page.locator('.notice button');
    if (await notice.first().isVisible()) await notice.first().click();
    await page.locator('#email').fill(email);
    await page.locator('#password').fill('SavingsPassword123');
    await page.locator('#confirmation').fill('SavingsPassword123');
    await page.locator('button[type=submit]').click();
    await page.waitForURL(base + '/verify');
    const mail = JSON.parse(await readFile(process.env.TEST_MAIL_DIR + '/' + createHash('sha256').update(email).digest('hex') + '.json', 'utf8'));
    await page.locator('#verification-code').fill(mail.code);
    await page.locator('#verification-code').press('Enter');
    await page.waitForURL(base + '/');
    await page.goto(base + '/savings');
    await page.getByRole('button', { name: '+ Створити ціль', exact: true }).click();
    await page.getByLabel('Назва цілі', { exact: true }).fill('Тестова подушка');
    await page.getByLabel('Цільова сума, UAH', { exact: true }).fill('12000.00');
    const deadline = new Date(); deadline.setUTCMonth(deadline.getUTCMonth() + 6, 1);
    await page.getByLabel('Накопичити до', { exact: true }).fill(deadline.toISOString().slice(0, 10));
    await page.getByRole('button', { name: 'Зберегти ціль', exact: true }).click();
    await page.getByRole('button', { name: '+ Додати внесок', exact: true }).click();
    assert.equal(await page.locator('.contribution-editor input').first().evaluate(input => input === document.activeElement), true, 'Contribution amount should receive focus');
    await page.getByLabel('Сума, UAH', { exact: true }).fill('1000,50');
    await page.getByRole('button', { name: 'Зберегти внесок', exact: true }).click();
    await page.locator('.contribution').filter({ hasText: '1' }).first().waitFor();
    await page.reload();
    await page.locator('.goal-card').filter({ hasText: 'Тестова подушка' }).click();
    await page.locator('.contribution').first().waitFor();
    await page.locator('.plan tbody tr').first().waitFor();
    assert.equal(await page.getByRole('button', { name: '+ Додати внесок', exact: true }).evaluate(button => getComputedStyle(button).backgroundColor), 'rgb(39, 213, 176)');
    const amounts = await page.locator('.plan tbody tr td:last-child').allTextContents();
    assert.equal(amounts.length, 6);
    const sum = amounts.reduce((sum, value) => sum + Math.round(Number(value.replace(/[^\d,.-]/g, '').replace(',', '.')) * 100), 0);
    assert.equal(sum, 1099950, 'Monthly plan must sum to the remaining target after contribution');
    for (const width of [375, 768, 1440]) {
      await page.setViewportSize({ width, height: 1000 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Overflow at ' + width);
      await page.screenshot({ path: '/artifacts/savings-' + width + '.png', fullPage: true });
    }
    await page.getByRole('button', { name: 'Скасувати ціль', exact: true }).click();
    await page.getByRole('button', { name: 'Підтвердити', exact: true }).click();
    await page.getByText('Ціль скасовано.', { exact: true }).waitFor();
    assert.equal(await page.locator('.goal-card').count(), 0);
    await page.getByRole('button', { name: 'Показати завершені та скасовані', exact: true }).click();
    await page.locator('.goal-card').filter({ hasText: 'Скасована' }).waitFor();
    await page.getByRole('button', { name: 'Зробити ціль активною', exact: true }).click();
    const restoredDeadline = new Date(); restoredDeadline.setUTCMonth(restoredDeadline.getUTCMonth() + 9, 1);
    await page.getByLabel('Новий строк цілі', { exact: true }).fill(restoredDeadline.toISOString().slice(0, 10));
    const restoreResponse = page.waitForResponse(response => response.url().endsWith('/reactivate') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Відновити ціль', exact: true }).click();
    assert.equal((await restoreResponse).status(), 200);
    await page.getByText('Ціль знову активна. Строк і план накопичення оновлено.', { exact: true }).waitFor();
    await page.locator('.plan tbody tr').first().waitFor();
    assert.equal(await page.locator('.plan tbody tr').count(), 9);
    assert.equal(await page.locator('.contribution').count(), 1);
    await page.getByRole('button', { name: 'Скасувати ціль', exact: true }).click();
    await page.getByRole('button', { name: 'Підтвердити', exact: true }).click();
    await page.getByText('Ціль скасовано.', { exact: true }).waitFor();
    await page.getByRole('button', { name: '+ Створити ціль', exact: true }).click();
    await page.getByLabel('Назва цілі', { exact: true }).fill('Наявна ціль');
    await page.getByLabel('Цільова сума, UAH', { exact: true }).fill('5000');
    await page.getByLabel('Накопичити до', { exact: true }).fill(deadline.toISOString().slice(0, 10));
    await page.getByRole('button', { name: 'Зберегти ціль', exact: true }).click();
    await page.locator('.detail h2').filter({ hasText: 'Наявна ціль' }).waitFor();
    await page.locator('.goal-card').filter({ hasText: 'Тестова подушка' }).click();
    await page.getByRole('button', { name: 'Перенести кошти в іншу ціль', exact: true }).click();
    assert.notEqual(await page.getByLabel('Куди перенести').inputValue(), 'new');
    await page.getByRole('button', { name: 'Підтвердити перенесення', exact: true }).click();
    await page.locator('.detail h2').filter({ hasText: 'Наявна ціль' }).waitFor();
    await page.locator('.contribution').first().waitFor();
    await page.locator('.goal-card').filter({ hasText: 'Тестова подушка' }).click();
    await page.getByRole('button', { name: 'Видалити порожню ціль', exact: true }).click();
    await page.getByRole('button', { name: 'Підтвердити', exact: true }).click();
    await page.getByText('Порожню ціль видалено.', { exact: true }).waitFor();
    assert.equal(await page.locator('.goal-card').filter({ hasText: 'Тестова подушка' }).count(), 0);
    await page.locator('.goal-card').filter({ hasText: 'Наявна ціль' }).click();
    await page.getByRole('button', { name: 'Перенести кошти в іншу ціль', exact: true }).click();
    await page.getByLabel('Назва нової цілі', { exact: true }).fill('Нова ціль після перенесення');
    await page.getByRole('button', { name: 'Підтвердити перенесення', exact: true }).click();
    await page.locator('.detail h2').filter({ hasText: 'Нова ціль після перенесення' }).waitFor();
    await page.locator('.contribution').first().waitFor();
    const balancesResponse = page.waitForResponse(response => response.url() === base + '/api/savings/goals' && response.request().method() === 'GET');
    await page.reload();
    const balances = await balancesResponse;
    const goals = (await balances.json()).goals;
    assert.equal(goals.reduce((sum, goal) => sum + Math.round(Number(goal.saved_amount) * 100), 0), 100050);
    assert.equal(goals.filter(goal => goal.status === 'active').length, 1);
    assert.deepEqual(errors, []);
    assert.equal(writes.length, 9); assert.ok(writes.every(write => write[2] < 300));
    console.log('Savings browser smoke passed:', JSON.stringify(writes));
  } catch (error) {
    console.error('Detail at failure:', await page.locator('.detail').innerText().catch(() => 'unavailable'));
    console.error('Browser errors:', errors);
    await page.screenshot({ path: '/artifacts/savings-failure.png', fullPage: true });
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
